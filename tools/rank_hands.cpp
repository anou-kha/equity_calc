// Ranks the 169 starting-hand classes (AA, AKs, AKo, ..., 32o) by their exact preflop equity
// against one random hand, and prints the table that src/hand_ranking.cpp includes:
//
//   poker_rank_hands > src/hand_ranking_table.inc
//
// One hand per class is enough: by suit symmetry, AsAh does exactly as well against a random hand
// as AdAc does. Each class is 1,225 opponent hands x 1,712,304 boards, 2.1 billion showdowns, so
// the whole table is about 355 billion: roughly 25 minutes in Release on 16 threads. Progress goes
// to stderr and the table to stdout.
#include <algorithm>
#include <chrono>
#include <cstdint>
#include <iomanip>
#include <iostream>
#include <string>
#include <string_view>
#include <variant>
#include <vector>

#include "poker/card.hpp"
#include "poker/equity.hpp"
#include "poker/range.hpp"

namespace {

constexpr std::string_view kRanks = "23456789TJQKA";

struct ClassResult {
  std::string name;
  uint64_t wins = 0;
  uint64_t ties = 0;
  uint64_t boards = 0;

  // Twice the expected pot share, as a whole number, so classes are compared exactly. Heads-up, a
  // tie always pays half the pot.
  uint64_t doubledShare() const { return 2 * wins + ties; }
  double equity() const {
    return static_cast<double>(doubledShare()) / static_cast<double>(2 * boards);
  }
};

}  // namespace

int main() {
  const auto random = std::get<poker::Range>(poker::parseRange("random"));
  const auto start = std::chrono::steady_clock::now();
  std::vector<ClassResult> results;

  // Scores one hand of a class against every hand it can meet, on every board.
  const auto rank = [&](std::string name, poker::Card first, poker::Card second) {
    poker::Range hand;
    hand.add({first, second});
    const std::vector<poker::Range> players = {hand, random};
    // By value: a reference into the temporary variant would dangle after this line.
    const auto result =
        std::get<poker::EquityResult>(poker::exactEquity(players, 0, 0, {.threads = 0}));
    results.push_back(
        {std::move(name), result.players[0].wins, result.players[0].ties, result.boards});
    const double seconds =
        std::chrono::duration<double>(std::chrono::steady_clock::now() - start).count();
    std::cerr << std::fixed << std::setprecision(2) << results.size() << "/169 "
              << results.back().name << ": " << 100.0 * results.back().equity() << "% ("
              << std::setprecision(0) << seconds << " s so far)\n";
  };

  // One hand of each class: a pair in spades and hearts, a suited hand in spades, and an offsuit
  // hand a spade and a heart.
  constexpr int kSpades = 3;
  constexpr int kHearts = 2;
  for (int high = poker::Card::kNumRanks - 1; high >= 0; --high) {
    for (int low = high; low >= 0; --low) {
      const std::string ranks{kRanks[static_cast<size_t>(high)], kRanks[static_cast<size_t>(low)]};
      if (high == low) {
        rank(ranks, poker::Card(high, kSpades), poker::Card(low, kHearts));
      } else {
        rank(ranks + "s", poker::Card(high, kSpades), poker::Card(low, kSpades));
        rank(ranks + "o", poker::Card(high, kSpades), poker::Card(low, kHearts));
      }
    }
  }

  // Best first. Equal shares (none are expected) keep the order above.
  std::stable_sort(results.begin(), results.end(), [](const ClassResult& a, const ClassResult& b) {
    return a.doubledShare() > b.doubledShare();
  });

  std::cout
      << "// Generated by poker_rank_hands (tools/rank_hands.cpp); don't edit by hand. Every\n"
         "// starting-hand class, best first: one hand of the class against all 1,225 others,\n"
         "// on all 1,712,304 boards each, as {class, wins, ties}.\n";
  for (const ClassResult& result : results) {
    if (result.boards != results.front().boards) {
      std::cerr << "error: " << result.name << " has " << result.boards << " boards\n";
      return 1;
    }
    std::cout << "{\"" << result.name << "\", " << result.wins << ", " << result.ties << "},  // "
              << std::fixed << std::setprecision(2) << 100.0 * result.equity() << "%\n";
  }
  return 0;
}
